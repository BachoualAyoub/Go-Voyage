CREATE TABLE destination (
    id_d BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    nom VARCHAR(100) NOT NULL,
    ville VARCHAR(100) NOT NULL,
    pays VARCHAR(70) NOT NULL,
    region VARCHAR(100) NOT NULL,
    ambiance VARCHAR(20) NOT NULL CHECK (ambiance IN ('MER', 'CULTURE', 'NATURE')),
    tarif_jour_tnd INTEGER NOT NULL CHECK (tarif_jour_tnd > 0),
    accroche VARCHAR(140) NOT NULL,
    description VARCHAR(750) NOT NULL
);

CREATE TABLE circuit (
    id_c BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietaire_id BIGINT REFERENCES utilisateur (id_u) ON DELETE CASCADE,
    nom VARCHAR(90) NOT NULL,
    description VARCHAR(300),
    budget_tnd INTEGER CHECK (budget_tnd BETWEEN 1 AND 1000000),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_circuit_proprietaire ON circuit (proprietaire_id);

CREATE TABLE etape_circuit (
    circuit_id BIGINT NOT NULL REFERENCES circuit (id_c) ON DELETE CASCADE,
    ordre INTEGER NOT NULL CHECK (ordre >= 0),
    destination_id BIGINT NOT NULL REFERENCES destination (id_d),
    jours INTEGER NOT NULL CHECK (jours BETWEEN 1 AND 30),
    PRIMARY KEY (circuit_id, ordre)
);
