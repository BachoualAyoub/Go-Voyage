CREATE TABLE hotel (
 id_h BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 destination_id BIGINT NOT NULL REFERENCES destination(id_d),
 nom VARCHAR(120) NOT NULL, ville VARCHAR(100) NOT NULL,
 description VARCHAR(1200) NOT NULL, etoiles INTEGER NOT NULL CHECK (etoiles BETWEEN 1 AND 5),
 tarif_nuit INTEGER NOT NULL CHECK (tarif_nuit > 0),
 chambres INTEGER NOT NULL CHECK (chambres BETWEEN 1 AND 500),
 capacite INTEGER NOT NULL CHECK (capacite BETWEEN 1 AND 10),
 image VARCHAR(400) NOT NULL, actif BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE vol (
 id_v BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 compagnie VARCHAR(80) NOT NULL, categorie VARCHAR(20) NOT NULL,
 depart VARCHAR(70) NOT NULL, arrivee VARCHAR(70) NOT NULL,
 heure_depart VARCHAR(5) NOT NULL, duree_minutes INTEGER NOT NULL,
 prix INTEGER NOT NULL, bagage VARCHAR(80) NOT NULL
);
CREATE TABLE reservation (
 id_r BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id_u) ON DELETE CASCADE,
 hotel_id BIGINT NOT NULL REFERENCES hotel(id_h),
 arrivee DATE NOT NULL, depart DATE NOT NULL, voyageurs INTEGER NOT NULL,
 chambres INTEGER NOT NULL, tarif_nuit INTEGER NOT NULL, montant INTEGER NOT NULL,
 statut VARCHAR(20) NOT NULL DEFAULT 'CONFIRMEE',
 cle VARCHAR(36) NOT NULL, cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (depart > arrivee), CHECK (voyageurs > 0 AND chambres > 0),
 CHECK (statut IN ('CONFIRMEE','ANNULEE')),
 UNIQUE (utilisateur_id, cle)
);
CREATE INDEX idx_reservation_disponibilite ON reservation(hotel_id,statut,arrivee,depart);
