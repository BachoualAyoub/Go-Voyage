CREATE TABLE publication (
 id_p BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id_u) ON DELETE CASCADE,
 titre VARCHAR(120) NOT NULL, texte VARCHAR(2000) NOT NULL,
 pays VARCHAR(70) NOT NULL, ville VARCHAR(100) NOT NULL,
 media_url VARCHAR(600), media_type VARCHAR(10), statut VARCHAR(20) NOT NULL DEFAULT 'PUBLIEE',
 cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (statut IN ('PUBLIEE','MASQUEE'))
);
CREATE TABLE avis (
 id_a BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publication_id BIGINT NOT NULL REFERENCES publication(id_p) ON DELETE CASCADE,
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id_u) ON DELETE CASCADE,
 texte VARCHAR(1000) NOT NULL, note INTEGER NOT NULL CHECK(note BETWEEN 1 AND 5),
 cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(publication_id,utilisateur_id)
);
CREATE TABLE appreciation (
 publication_id BIGINT NOT NULL REFERENCES publication(id_p) ON DELETE CASCADE,
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id_u) ON DELETE CASCADE,
 PRIMARY KEY(publication_id,utilisateur_id)
);
CREATE TABLE signalement (
 id_s BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 publication_id BIGINT NOT NULL REFERENCES publication(id_p) ON DELETE CASCADE,
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateur(id_u) ON DELETE CASCADE,
 motif VARCHAR(500) NOT NULL, statut VARCHAR(15) NOT NULL DEFAULT 'OUVERT',
 cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(publication_id,utilisateur_id), CHECK(statut IN ('OUVERT','TRAITE'))
);
